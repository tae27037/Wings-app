const Ctx = createContext(null);
export const useApp = () => useContext(Ctx);
const load = (k, d) => {
  try {
    return localStorage.getItem(k) || d;
  } catch {
    return d;
  }
};

export function AppProvider({ children }) {
  const [lang, setLang] = useState(() => load("lang", "cs"));
  const [theme, setTheme] = useState(() =>
    load(
      "theme",
      typeof matchMedia === "function" &&
        matchMedia("(prefers-color-scheme: light)").matches
        ? "light"
        : "dark",
    ),
  );
  const [cur, setCur] = useState(() => load("cur", "CZK"));
  useEffect(() => {
    document.documentElement.dataset.theme = theme;
    document.documentElement.lang = lang;
    try {
      localStorage.setItem("lang", lang);
      localStorage.setItem("theme", theme);
      localStorage.setItem("cur", cur);
    } catch {
      /* ignore */
    }
  }, [lang, theme, cur]);

  const t = useCallback((k) => DICT[lang][k] ?? k, [lang]);
  const tr = (o) => o[lang];
  const money = (czk) =>
    new Intl.NumberFormat(LOCALE[lang], {
      style: "currency",
      currency: cur,
      minimumFractionDigits: 0,
      maximumFractionDigits: cur === "CZK" ? 0 : 2,
    }).format(czk * RATES[cur]);

  return (
    <Ctx.Provider
      value={{ lang, setLang, theme, setTheme, cur, setCur, t, tr, money }}
    >
      {children}
    </Ctx.Provider>
  );
}
